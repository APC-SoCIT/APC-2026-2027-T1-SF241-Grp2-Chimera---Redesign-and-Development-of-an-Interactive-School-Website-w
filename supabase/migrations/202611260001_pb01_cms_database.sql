-- Website Content Columns START
-- The reference schema numbers cms_content rows automatically; make sure the live table does too.
do $$ begin
    if (select attidentity from pg_attribute where attrelid = 'public.cms_content'::regclass and attname = 'id') = '' then
        alter table public.cms_content alter column id add generated by default as identity;
        perform setval(pg_get_serial_sequence('public.cms_content', 'id'), coalesce((select max(id) from public.cms_content), 0) + 1, false);
    end if;
end $$;

alter table public.cms_content
    add column if not exists summary text not null default '',
    add column if not exists images jsonb not null default '[]'::jsonb,
    add column if not exists created_at timestamptz not null default now(),
    add column if not exists deleted_at timestamptz;               -- set while the item is in Trash
do $$ begin
    if not exists (select 1 from pg_constraint where conrelid = 'public.cms_content'::regclass and conname = 'cms_content_images_check') then
        alter table public.cms_content add constraint cms_content_images_check
            check (jsonb_typeof(images) = 'array' and jsonb_array_length(images) <= 4);
    end if;
end $$;

alter table public.resources add column if not exists deleted_at timestamptz;
-- Website Content Columns END

-- Access START
-- Same rule as the staff portal's Admin routes: an active Admin with a live staff session.
create or replace function public.require_content_admin()
returns bigint language plpgsql stable security definer set search_path = ''
as $$
declare
    actor_id bigint;
begin
    if not public.has_active_admin_access() then
        raise insufficient_privilege using message = 'Admin access required';
    end if;
    select id into actor_id from public.users where auth_user_id = auth.uid();
    return actor_id;
end;
$$;

-- Website content stays behind the functions: no direct table access from the site.
revoke all on public.cms_content from anon, authenticated;
-- Visitors still read published public PDFs directly; Trash hides a resource from them too.
drop policy if exists "Read public published resources" on public.resources;
create policy "Read public published resources" on public.resources for select to anon, authenticated
    using (status = 'published' and visibility = 'public' and deleted_at is null);
grant select (deleted_at) on public.resources to anon, authenticated;
-- Access END

-- Manage Website Content START
create function public.cms_list_content()
returns table ("contentId" bigint, "contentType" text, "title" text, "slug" text, "summary" text, "body" text,
               "images" jsonb, "eventStartsAt" timestamptz, "status" text, "publishedAt" timestamptz,
               "updatedAt" timestamptz, "deletedAt" timestamptz, "createdByName" text, "updatedByName" text)
language plpgsql stable security definer set search_path = ''
as $$
begin
    perform public.require_content_admin();
    return query
    select c.id, c.content_type, c.title, c.slug, c.summary, c.body, c.images, c.event_date, c.status,
           c.published_at, c.updated_at, c.deleted_at, cu.full_name, uu.full_name
    from public.cms_content c
    left join public.users cu on cu.id = c.created_by
    left join public.users uu on uu.id = c.updated_by
    order by c.updated_at desc;
end;
$$;

-- p_id null creates a draft; otherwise updates an existing item's text (status unchanged).
create function public.cms_save_content(
    p_id bigint, p_type text, p_title text, p_slug text, p_summary text, p_body text,
    p_event_starts_at timestamptz default null, p_images jsonb default '[]'::jsonb
)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare
    actor_id bigint := public.require_content_admin();
    previous jsonb;
    saved_id bigint;
begin
    if p_type not in ('announcement', 'event', 'page') then
        raise invalid_parameter_value using message = 'Unknown content type';
    end if;
    if length(btrim(coalesce(p_title, ''))) = 0 or length(p_title) > 200 then
        raise invalid_parameter_value using message = 'Title must be 1 to 200 characters';
    end if;
    if coalesce(p_slug, '') !~ '^[a-z0-9]+(-[a-z0-9]+)*$' or length(p_slug) > 200 then
        raise invalid_parameter_value using message = 'Page identifier must use lowercase letters, numbers and hyphens';
    end if;
    if length(coalesce(p_body, '')) > 50000 or length(coalesce(p_summary, '')) > 500 then
        raise invalid_parameter_value using message = 'Text is too long';
    end if;
    if p_type = 'event' and p_event_starts_at is null then
        raise invalid_parameter_value using message = 'Choose the event date';
    end if;

    if p_id is null then
        insert into public.cms_content (content_type, title, slug, summary, body, event_date, images, created_by, updated_by)
        values (p_type, btrim(p_title), p_slug, coalesce(p_summary, ''), coalesce(p_body, ''), p_event_starts_at,
                coalesce(p_images, '[]'::jsonb), actor_id, actor_id)
        returning id into saved_id;
    else
        select to_jsonb(c) - 'body' into previous from public.cms_content c where c.id = p_id and c.deleted_at is null;
        if previous is null then
            raise no_data_found using message = 'Content not found';
        end if;
        update public.cms_content
        set content_type = p_type, title = btrim(p_title), slug = p_slug, summary = coalesce(p_summary, ''),
            body = coalesce(p_body, ''), event_date = p_event_starts_at, images = coalesce(p_images, '[]'::jsonb),
            updated_by = actor_id, updated_at = now()
        where id = p_id
        returning id into saved_id;
    end if;

    insert into public.audit_logs (actor_user_id, action, entity_type, entity_id, old_value, new_value)
    values (actor_id, case when p_id is null then 'cms.create' else 'cms.update' end, 'cms_content', saved_id,
            previous, jsonb_build_object('content_type', p_type, 'title', btrim(p_title), 'slug', p_slug));
    return saved_id;
end;
$$;

-- Published, public items for the website. Visitors never see drafts, archived items or Trash.
create function public.cms_public_content()
returns table ("contentId" bigint, "contentType" text, "title" text, "slug" text, "summary" text, "body" text,
               "images" jsonb, "eventStartsAt" timestamptz, "publishedAt" timestamptz, "updatedAt" timestamptz)
language sql stable security definer set search_path = ''
as $$
    select c.id, c.content_type, c.title, c.slug, c.summary, c.body, c.images, c.event_date, c.published_at, c.updated_at
    from public.cms_content c
    where c.status = 'published' and c.deleted_at is null
    order by c.published_at desc nulls last;
$$;
-- Manage Website Content END

-- Manage Downloadable Resources START
create function public.cms_list_resources()
returns table ("resourceId" bigint, "title" text, "category" text, "storagePath" text, "fileSizeBytes" integer,
               "status" text, "visibility" text, "updatedAt" timestamptz, "deletedAt" timestamptz, "uploadedByName" text)
language plpgsql stable security definer set search_path = ''
as $$
begin
    perform public.require_content_admin();
    return query
    select r.id, r.title, r.category, r.storage_path, r.file_size_bytes, r.status, r.visibility,
           r.updated_at, r.deleted_at, u.full_name
    from public.resources r
    left join public.users u on u.id = r.uploaded_by
    order by r.updated_at desc;
end;
$$;

-- Called after the PDF is uploaded to resource-files. p_id null creates a draft record.
create function public.cms_save_resource(
    p_id bigint, p_title text, p_category text, p_storage_path text, p_file_size_bytes integer, p_visibility text
)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare
    actor_id bigint := public.require_content_admin();
    previous jsonb;
    saved_id bigint;
begin
    if length(btrim(coalesce(p_title, ''))) = 0 or length(p_title) > 200 then
        raise invalid_parameter_value using message = 'Title must be 1 to 200 characters';
    end if;
    if length(btrim(coalesce(p_category, ''))) = 0 or length(p_category) > 60 then
        raise invalid_parameter_value using message = 'Category must be 1 to 60 characters';
    end if;
    if p_visibility not in ('public', 'private') then
        raise invalid_parameter_value using message = 'Unknown visibility';
    end if;
    if coalesce(p_storage_path, '') !~ '^[A-Za-z0-9._/-]+\.pdf$' then
        raise invalid_parameter_value using message = 'Resource file must be a PDF in resource-files';
    end if;

    if p_id is null then
        insert into public.resources (title, category, storage_path, file_size_bytes, visibility, uploaded_by)
        values (btrim(p_title), btrim(p_category), p_storage_path, p_file_size_bytes, p_visibility, actor_id)
        returning id into saved_id;
    else
        select to_jsonb(r) into previous from public.resources r where r.id = p_id and r.deleted_at is null;
        if previous is null then
            raise no_data_found using message = 'Resource not found';
        end if;
        update public.resources
        set title = btrim(p_title), category = btrim(p_category), storage_path = p_storage_path,
            file_size_bytes = p_file_size_bytes, visibility = p_visibility, updated_at = now()
        where id = p_id
        returning id into saved_id;
    end if;

    insert into public.audit_logs (actor_user_id, action, entity_type, entity_id, old_value, new_value)
    values (actor_id, case when p_id is null then 'resource.create' else 'resource.update' end, 'resources', saved_id,
            previous, jsonb_build_object('title', btrim(p_title), 'storage_path', p_storage_path, 'visibility', p_visibility));
    return saved_id;
end;
$$;
-- Manage Downloadable Resources END

-- Publish, Trash, Restore, Delete START (p_kind: 'content' or 'resource')
create function public.cms_set_status(p_kind text, p_id bigint, p_status text)
returns void language plpgsql security definer set search_path = ''
as $$
declare
    actor_id bigint := public.require_content_admin();
    previous text;
begin
    if p_status not in ('draft', 'published', 'archived') then
        raise invalid_parameter_value using message = 'Unknown status';
    end if;
    if p_kind = 'content' then
        select status into previous from public.cms_content where id = p_id and deleted_at is null;
        if previous is null then raise no_data_found using message = 'Content not found'; end if;
        update public.cms_content
        set status = p_status, updated_by = actor_id, updated_at = now(),
            published_at = case when p_status = 'published' then coalesce(published_at, now()) else published_at end
        where id = p_id;
    elsif p_kind = 'resource' then
        select status into previous from public.resources where id = p_id and deleted_at is null;
        if previous is null then raise no_data_found using message = 'Resource not found'; end if;
        update public.resources set status = p_status, updated_at = now() where id = p_id;
    else
        raise invalid_parameter_value using message = 'Unknown item kind';
    end if;

    insert into public.audit_logs (actor_user_id, action, entity_type, entity_id, old_value, new_value)
    values (actor_id, 'cms.status', case when p_kind = 'content' then 'cms_content' else 'resources' end, p_id,
            jsonb_build_object('status', previous), jsonb_build_object('status', p_status));
end;
$$;

create function public.cms_trash(p_kind text, p_id bigint, p_restore boolean default false)
returns void language plpgsql security definer set search_path = ''
as $$
declare
    actor_id bigint := public.require_content_admin();
    changed integer;
begin
    if p_kind = 'content' then
        update public.cms_content
        set deleted_at = case when p_restore then null else now() end, updated_by = actor_id, updated_at = now()
        where id = p_id and (deleted_at is null) = (not p_restore);
    elsif p_kind = 'resource' then
        update public.resources
        set deleted_at = case when p_restore then null else now() end, updated_at = now()
        where id = p_id and (deleted_at is null) = (not p_restore);
    else
        raise invalid_parameter_value using message = 'Unknown item kind';
    end if;
    get diagnostics changed = row_count;
    if changed = 0 then raise no_data_found using message = 'Item not found'; end if;

    insert into public.audit_logs (actor_user_id, action, entity_type, entity_id)
    values (actor_id, case when p_restore then 'cms.restore' else 'cms.trash' end,
            case when p_kind = 'content' then 'cms_content' else 'resources' end, p_id);
end;
$$;

-- Permanent delete, only from Trash. For a resource it returns the PDF path so the workspace
-- can remove the file from resource-files afterwards.
create function public.cms_delete(p_kind text, p_id bigint)
returns text language plpgsql security definer set search_path = ''
as $$
declare
    actor_id bigint := public.require_content_admin();
    previous jsonb;
    file_path text;
begin
    if p_kind = 'content' then
        delete from public.cms_content c where c.id = p_id and c.deleted_at is not null
        returning to_jsonb(c.*) - 'body' into previous;
    elsif p_kind = 'resource' then
        delete from public.resources r where r.id = p_id and r.deleted_at is not null
        returning to_jsonb(r.*), r.storage_path into previous, file_path;
    else
        raise invalid_parameter_value using message = 'Unknown item kind';
    end if;
    if previous is null then raise no_data_found using message = 'Item is not in Trash'; end if;

    insert into public.audit_logs (actor_user_id, action, entity_type, entity_id, old_value)
    values (actor_id, 'cms.delete', case when p_kind = 'content' then 'cms_content' else 'resources' end, p_id, previous);
    return file_path;
end;
$$;
-- Publish, Trash, Restore, Delete END

