-- PB-01 Manage Website Content: the content workspace saves to the school database.
-- Announcements, events and pages go to cms_content; PDF resources to resources; images to the
-- public content-images bucket and PDFs to the existing public resource-files bucket.
-- Every change goes through the cms_* functions below, which allow only an active Admin with a
-- live staff session and write audit_logs. Visitors read published items through
-- cms_public_content() and the existing resources policy.
-- After applying, set VITE_CMS_DATABASE=true on the site and redeploy.

